def find_latest_sol(sol_dir: Path) -> Path:
    """
    Scan sol_dir and return the path of the most recently modified .sol file.

    Why "most recently modified" and not alphabetical?
    --------------------------------------------------
    Your filenames contain a date-time tag (model_name_YYYYMMDD_HHMMSS.sol).
    Sorting by modification time is more robust than sorting by name because:
      - It works even if someone renames a file or uses a different date format.
      - It always gives you the file that was written last, which is the run
        you just finished.

    Raises FileNotFoundError if the folder does not exist or has no .sol files.
    """
    sol_dir = Path(sol_dir)

    if not sol_dir.exists():
        raise FileNotFoundError(
            f"SOL directory not found: '{sol_dir.absolute()}'\n"
            f"Check that sol_dir points to the right folder."
        )

    # Collect all .sol files in the folder (not recursive)
    sol_files = list(sol_dir.glob("*.sol"))

    if not sol_files:
        raise FileNotFoundError(
            f"No .sol files found in '{sol_dir.absolute()}'\n"
            f"Has the model finished solving?"
        )

    # Sort by last-modified time, newest first, and return the top one
    latest = max(sol_files, key=lambda p: p.stat().st_mtime)

    print(f"[find_latest_sol] Found {len(sol_files)} .sol file(s) in '{sol_dir}'")
    print(f"[find_latest_sol] Using latest: '{latest.name}'")

    return latest


