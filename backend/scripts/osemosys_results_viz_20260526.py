def plot_capacity(sol: dict,
                  variable_name: str = "TotalCapacityAnnual",
                  tech_prefix: str   = "PWR",
                  units: str         = "GW") -> None:
    """
    Bar chart: installed capacity by technology over time.

    Parameters
    ----------
    sol           : the loaded sol dictionary
    variable_name : one of "TotalCapacityAnnual", "NewCapacity",
                    "AccumulatedNewCapacity"
    tech_prefix   : filter to technologies whose names start with this string
                    e.g. "PWR" keeps only power-sector technologies
    units         : "GW" (converts from PJ) or "PJ" (no conversion)
    """

    # --- Get data ---
    df = sol_variable_to_df(sol, variable_name, ["REGION", "TECHNOLOGY", "YEAR"])
    if df.empty:
        print(f"  No data for '{variable_name}' — skipping plot.")
        return

    # --- Filter & aggregate ---
    df = df[df["TECHNOLOGY"].str.startswith(tech_prefix)]          # keep only wanted techs
    df = _apply_year_filter(df, years_to_plot)                      # apply year filter
    df = df.groupby(["TECHNOLOGY", "YEAR"], as_index=False)["VALUE"].sum()
    df = df[df["VALUE"] > 1e-5]                                    # drop near-zero rows
    df["YEAR"] = df["YEAR"].astype(str)

    if df.empty:
        print(f"  All values were near-zero for '{variable_name}' — skipping.")
        return

    # --- Unit conversion ---
    # OSeMOSYS capacity is stored in PJ/yr; 1 GW = 31.536 PJ/yr
    if units == "GW":
        df["VALUE"] = df["VALUE"] / 31.536

    # --- Plot ---
    fig = px.bar(
        df,
        x="YEAR",
        y="VALUE",
        color="TECHNOLOGY",
        title=f"Installed Capacity by Technology — {variable_name}",
        labels={"VALUE": units, "YEAR": "Year", "TECHNOLOGY": "Technology"},
        color_discrete_map=COLOR_MAP,
    )
    fig.update_layout(
        legend=dict(traceorder="normal"),
        xaxis=dict(type="category"),   # treat years as categories (no gaps)
    )
    fig.show()
    graph_path = graphs_dir / f"capacity_{variable_name}.html"
    fig.write_html(str(graph_path))
    print(f"  Graph saved: {graph_path}")

    # --- Save static PNG (Matplotlib) ---
    _save_matplotlib_bar(
        df, x_col="YEAR", y_col="VALUE", color_col="TECHNOLOGY",
        title=f"Installed Capacity by Technology — {variable_name}",
        xlabel="Year", ylabel=units,
        filepath=graphs_dir_static / f"capacity_{variable_name}.png",
        color_map=COLOR_MAP,
        x_order=sorted(df["YEAR"].unique()),
    )

    # --- Save CSV ---
    out_path = os.path.join(output_dir, f"capacity_{variable_name}.csv")
    df.to_csv(out_path, index=False)
    print(f"  Saved: {out_path}")


def plot_generation(sol: dict,
                    variable_name: str = "ProductionByTechnology",
                    tech_prefix: str   = "PWR",
                    units: str         = "TWh",
                    timeslice_steps: int = 1) -> None:
    """
    Bar chart: electricity generation by technology over time.

    Parameters
    ----------
    sol              : the loaded sol dictionary
    variable_name    : typically "ProductionByTechnology"
    tech_prefix      : filter prefix (default "PWR")
    units            : "TWh" (converts from PJ) or "PJ"
    timeslice_steps  : set to div — controls whether the x-axis shows
                       annual totals (1) or individual timeslice bars (>1)
    """

    # --- Get data ---
    df = sol_variable_to_df(
        sol, variable_name,
        ["REGION", "TIMESLICE", "TECHNOLOGY", "FUEL", "YEAR"]
    )
    if df.empty:
        print(f"  No data for '{variable_name}' — skipping plot.")
        return

    # --- Filter by technology prefix and year ---
    df = df[df["TECHNOLOGY"].str.startswith(tech_prefix)]
    df["YEAR"] = df["YEAR"].astype(int)
    df = _apply_year_filter(df, years_to_plot)                      # apply year filter

    # --- Build time axis ---
    if timeslice_steps <= 1:
        # Annual view: one bar per year
        df["TIME"]     = df["YEAR"].astype(str)
        df["TIME_NUM"] = df["YEAR"]
    else:
        # Sub-annual view: one bar per timeslice per year
        # Timeslice names look like S101, S202, etc.
        # We extract the block number (e.g. "1" from "S101") for ordering
        df["BLOCK"]    = df["TIMESLICE"].str[1:3].astype(int)
        df["TIME"]     = df["YEAR"].astype(str) + "_" + df["TIMESLICE"]
        df["TIME_NUM"] = df["YEAR"] + (df["BLOCK"] - 1) / df["BLOCK"].max()

    # --- Aggregate ---
    df_agg = (
        df.groupby(["TECHNOLOGY", "TIME", "TIME_NUM"], as_index=False)["VALUE"]
        .sum()
    )
    df_agg = df_agg[df_agg["VALUE"].abs() > 1e-5]   # drop near-zero rows
    df_agg = df_agg.sort_values("TIME_NUM")          # chronological order

    if df_agg.empty:
        print(f"  All values were near-zero for '{variable_name}' — skipping.")
        return

    # --- Unit conversion ---
    # OSeMOSYS energy is in PJ; 1 TWh = 3.6 PJ
    if units == "TWh":
        df_agg["VALUE"] = df_agg["VALUE"] / 3.6

    # --- Plot ---
    fig = px.bar(
        df_agg,
        x="TIME",
        y="VALUE",
        color="TECHNOLOGY",
        title=f"Electricity Generation by Technology — {variable_name}",
        labels={"VALUE": units, "TIME": "Year", "TECHNOLOGY": "Technology"},
        color_discrete_map=COLOR_MAP,
    )
    fig.update_xaxes(
        categoryorder="array",
        categoryarray=df_agg["TIME"].tolist()   # enforce chronological order
    )
    fig.update_layout(legend=dict(traceorder="normal"))
    fig.show()
    graph_path = graphs_dir / f"generation_{variable_name}_{timeslice_steps}TS.html"
    fig.write_html(str(graph_path))
    print(f"  Graph saved: {graph_path}")

    # --- Save static PNG (Matplotlib) ---
    _save_matplotlib_bar(
        df_agg, x_col="TIME", y_col="VALUE", color_col="TECHNOLOGY",
        title=f"Electricity Generation by Technology — {variable_name}",
        xlabel="Year", ylabel=units,
        filepath=graphs_dir_static / f"generation_{variable_name}_{timeslice_steps}TS.png",
        color_map=COLOR_MAP,
        x_order=df_agg["TIME"].tolist(),
    )

    # --- Save CSV ---
    out_path = os.path.join(output_dir, f"generation_{variable_name}_{timeslice_steps}TS.csv")
    df_agg.to_csv(out_path, index=False)
    print(f"  Saved: {out_path}")



def plot_generation_annual(sol: dict,
                           variable_name: str = "ProductionByTechnologyAnnual",
                           tech_prefix: str   = "PWR",
                           units: str         = "TWh") -> None:
    """
    Bar chart: annual electricity generation by technology, one bar per year.

    This function is designed for variables that are already summed over
    timeslices — specifically ProductionByTechnologyAnnual, which has
    dimensions (REGION, TECHNOLOGY, FUEL, YEAR) with no TIMESLICE column.

    Use this instead of plot_generation() when you want clean annual totals
    without sub-annual breakdown, regardless of how many timeslices the model
    uses.

    Parameters
    ----------
    sol           : the loaded sol dictionary
    variable_name : "ProductionByTechnologyAnnual" (default) or any other
                    variable with dimensions (REGION, TECHNOLOGY, FUEL, YEAR)
    tech_prefix   : filter to technologies whose names start with this string
    units         : "TWh" (converts from PJ) or "PJ"
    """

    # --- Get data ---
    # Note: no TIMESLICE dimension — this variable is already annual
    df = sol_variable_to_df(
        sol, variable_name,
        ["REGION", "TECHNOLOGY", "FUEL", "YEAR"]
    )
    if df.empty:
        print(f"  No data for '{variable_name}' — skipping plot.")
        return

    # --- Filter by technology prefix and year ---
    df = df[df["TECHNOLOGY"].str.startswith(tech_prefix)]
    df["YEAR"] = df["YEAR"].astype(int)
    df = _apply_year_filter(df, years_to_plot)

    # --- Aggregate: sum over REGION and FUEL, keep TECHNOLOGY and YEAR ---
    # Multiple fuels can be produced by the same technology (e.g. a CHP plant)
    # so we sum across fuels to get total generation per technology per year.
    df_agg = (
        df.groupby(["TECHNOLOGY", "YEAR"], as_index=False)["VALUE"]
        .sum()
    )
    df_agg = df_agg[df_agg["VALUE"].abs() > 1e-5]   # drop near-zero rows
    df_agg = df_agg.sort_values("YEAR")              # chronological order

    if df_agg.empty:
        print(f"  All values were near-zero for '{variable_name}' — skipping.")
        return

    # --- Unit conversion ---
    # OSeMOSYS energy is in PJ; 1 TWh = 3.6 PJ
    if units == "TWh":
        df_agg["VALUE"] = df_agg["VALUE"] / 3.6

    df_agg["YEAR"] = df_agg["YEAR"].astype(str)   # string for categorical x-axis

    # --- Plot ---
    fig = px.bar(
        df_agg,
        x="YEAR",
        y="VALUE",
        color="TECHNOLOGY",
        title=f"Annual Generation by Technology — {variable_name}",
        labels={"VALUE": units, "YEAR": "Year", "TECHNOLOGY": "Technology"},
        color_discrete_map=COLOR_MAP,
    )
    fig.update_layout(
        legend=dict(traceorder="normal"),
        xaxis=dict(type="category"),   # treat years as categories (no gaps)
    )
    fig.show()
    graph_path = graphs_dir / f"generation_annual_{variable_name}.html"
    fig.write_html(str(graph_path))
    print(f"  Graph saved: {graph_path}")

    # --- Save static PNG (Matplotlib) ---
    _save_matplotlib_bar(
        df_agg, x_col="YEAR", y_col="VALUE", color_col="TECHNOLOGY",
        title=f"Annual Generation by Technology — {variable_name}",
        xlabel="Year", ylabel=units,
        filepath=graphs_dir_static / f"generation_annual_{variable_name}.png",
        color_map=COLOR_MAP,
        x_order=sorted(df_agg["YEAR"].unique()),
    )

    # --- Save CSV ---
    out_path = os.path.join(output_dir, f"generation_annual_{variable_name}.csv")
    df_agg.to_csv(out_path, index=False)
    print(f"  Saved: {out_path}")

