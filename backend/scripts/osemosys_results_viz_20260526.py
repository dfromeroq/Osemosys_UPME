        print(f"\n--- {plot_type.upper()}: {varname} ---")

        # Get the right function from the dispatcher
        plot_fn = plot_dispatcher.get(plot_type)
        if plot_fn is None:
            print(f"  WARNING: unknown plot type '{plot_type}' — skipping.")
            continue

