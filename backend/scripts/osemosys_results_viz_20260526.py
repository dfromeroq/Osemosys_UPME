def _apply_year_filter(df: pd.DataFrame, years: list) -> pd.DataFrame:
    """
    Filter a DataFrame to only include rows whose YEAR column is in the
    years_to_plot list defined in USER SETTINGS.

    If years is None (the default), the DataFrame is returned unchanged —
    meaning all years in the solution are plotted.

    This helper is called internally by every plot function, so you never
    need to call it yourself.  Just set years_to_plot at the top of the
    script and every chart will respect it automatically.
    """
    if years is None:
        return df   # no filter — plot everything

    # Convert year values to int for reliable comparison, then filter
    df = df.copy()
    df["YEAR"] = df["YEAR"].astype(int)
    df = df[df["YEAR"].isin([int(y) for y in years])]

    if df.empty:
        print(f"  WARNING: year filter {years} removed all rows. "
              f"Check that years_to_plot matches the years in your model.")
    return df



# ================================================================================
# SECTION 2 – SOL-FILE READERS
# ================================================================================
#
# What we want from EVERY reader is the same thing:
#   A pandas DataFrame with exactly two columns:
#       "Name"   →  the full variable label  e.g. "NewCapacity(RE1_PWRSOL_2030)"
#       "Primal" →  the numeric value        e.g.  0.45
#
# Once we have that DataFrame we pass it to solution_to_dict() which turns it
# into the `sol` dictionary used by every plotting function.
# ================================================================================


def read_gurobi_sol(filename: str) -> pd.DataFrame:
    """
    Read a Gurobi .sol file and return a tidy two-column DataFrame.

    Gurobi .sol format looks like this:
        # Solution for model OBJ
        # Objective value = 1.31e+06
        TotalDiscountedCost(RE1_2022)   272355.38
        NewCapacity(RE1_PWRSOL_2030)    0.45
        ...

    Lines starting with '#' are comments and are skipped.
    Each data line has the form:   VariableName(indices)   value
    """
    rows = []

    with open(filename, "r") as f:
        for line in f:
            line = line.strip()

            # Skip blank lines and comment lines (start with '#')
            if not line or line.startswith("#"):
                continue

            # Split into at most 2 parts: the name and the value
            # We use maxsplit=1 to handle any extra spaces
            parts = line.split(None, 1)
            if len(parts) != 2:
                continue   # skip malformed lines

            name  = parts[0]   # e.g. "NewCapacity(RE1_PWRSOL_2030)"
            value = parts[1]   # e.g. "0.45"

            # Convert value to float (Gurobi uses scientific notation sometimes)
            try:
                value = float(value)
            except ValueError:
                continue   # skip lines whose value cannot be parsed

            rows.append({"Name": name, "Primal": value})

    df = pd.DataFrame(rows)
    print(f"[Gurobi reader] Read {len(df)} variable entries from '{filename}'")
    return df


def read_highs_sol(filename: str) -> pd.DataFrame:
    """
    Read a HiGHS .sol file and return the same two-column DataFrame.

    HiGHS table format has 7+ columns per row:
        Index  Status  Lower  Upper  Primal  Dual  VariableName

    We extract only Name (last column) and Primal (5th column).
    """
    rows = []

    with open(filename, "r") as f:
        for line in f:
            parts = line.strip().split()

            # Lines with fewer than 7 parts are headers or blanks
            if len(parts) < 7:
                continue

            # The first 6 columns are numeric metadata; the rest is the name
            # (names can contain spaces, so we join anything after column 6)
            try:
                primal = float(parts[4])
            except ValueError:
                continue   # skip header rows whose 5th item is not a number

            name = " ".join(parts[6:])
            rows.append({"Name": name, "Primal": primal})

    df = pd.DataFrame(rows)
    print(f"[HiGHS reader] Read {len(df)} variable entries from '{filename}'")
    return df


def read_glpk_sol(filename: str) -> pd.DataFrame:
    """
    Read a GLPK .sol file and return the same two-column DataFrame.

    GLPK .sol format (when Pyomo writes it with symbolic labels) looks like:
        j NewCapacity(RE1_PWRSOL_2030)   0   0.45   0
        j TotalDiscountedCost(RE1_2022)  0   272355.38  0
        ...

    Lines starting with 'j' are variable rows.
    Column layout:  j  Name  status  primal  dual
    """
    rows = []

    with open(filename, "r") as f:
        for line in f:
            parts = line.strip().split()

            # GLPK variable rows start with 'j'
            if len(parts) < 4 or parts[0] != "j":
                continue

            name = parts[1]   # variable name with indices

            # Primal value is the 4th column (index 3)
            try:
                primal = float(parts[3])
            except ValueError:
                continue

            rows.append({"Name": name, "Primal": primal})

    df = pd.DataFrame(rows)
    print(f"[GLPK reader] Read {len(df)} variable entries from '{filename}'")
    return df


