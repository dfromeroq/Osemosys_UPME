# SECTION 4 – SMART INDEX PARSER: DataFrame → sol dict
# ================================================================================

def _dataframe_to_sol_dict(df: pd.DataFrame,
                            tech_set: set,
                            fuel_set: set,
                            region_set: set) -> dict:
    """
    Convert a two-column DataFrame (Name, Primal) into the `sol` dictionary.

    The challenge: OSeMOSYS variable names use underscores both as separators
    between indices AND within technology/fuel names themselves.
    Example:  RateOfActivity(RE1_S101_BACKSTOP_1_1_2022)
              The indices are: RE1 | S101 | BACKSTOP_1 | 1 | 2022
              But naively splitting on '_' would give 6 wrong pieces.

    Solution: we build a lookup set of all known multi-word names (technologies,
    fuels, regions) and try to match the longest known label at each position.
    This is the same approach that worked for HiGHS in your original script.

    Returns
    -------
    sol : dict
        { "VariableName": { (idx1, idx2, ...): value } }
    """

    # Sort known labels longest-first so we always try the longest match first
    # This prevents "BACKSTOP" from matching before "BACKSTOP_1"
    all_labels = sorted(
        tech_set | fuel_set | region_set,
        key=len, reverse=True
    )
    label_lookup = set(all_labels)

    sol = {}

    for _, row in df.iterrows():
        name   = str(row["Name"])
        primal = row["Primal"]

        # Skip entries that don't have the expected (indices) structure
        if "(" not in name or ")" not in name:
            continue

        # Split into variable name and the indices part
        # e.g.  "NewCapacity(RE1_PWRSOL_2030)"
        #     → varname = "NewCapacity",  indices_str = "RE1_PWRSOL_2030"
        varname, rest = name.split("(", 1)
        indices_str   = rest.rstrip(")")   # remove closing bracket

        # Tokenise by splitting on underscores
        tokens = indices_str.split("_")

        # Greedily match tokens to known labels (longest match first)
        idx    = []
        i      = 0
        while i < len(tokens):
            matched = False
            # Try combining up to 5 consecutive tokens into one label
            max_span = min(5, len(tokens) - i)
            for span in range(max_span, 0, -1):
                candidate = "_".join(tokens[i : i + span])
                if candidate in label_lookup:
                    idx.append(candidate)
                    i += span
                    matched = True
                    break
            if not matched:
                # No known label matched — keep the single token as-is
                idx.append(tokens[i])
                i += 1

        # Build the dictionary key: single string for 1-D, tuple for N-D
        index_key = idx[0] if len(idx) == 1 else tuple(idx)

        # Add to sol dict
        if varname not in sol:
            sol[varname] = {}
        sol[varname][index_key] = primal

    return sol


def sol_variable_to_df(sol: dict, varname: str, dimnames: list) -> pd.DataFrame:
    """
    Extract one variable from the sol dict and return it as a tidy DataFrame.

    Parameters
    ----------
    sol      : the sol dictionary produced by load_solution()
    varname  : the OSeMOSYS variable name, e.g. "NewCapacity"
    dimnames : list of column names for each index dimension,
               e.g. ["REGION", "TECHNOLOGY", "YEAR"]

    Returns
    -------
    DataFrame with columns = dimnames + ["VALUE"]

    Example
    -------
    df = sol_variable_to_df(sol, "NewCapacity", ["REGION", "TECHNOLOGY", "YEAR"])
    """
    if varname not in sol:
        print(f"  WARNING: Variable '{varname}' not found in sol. "
              f"Available: {list(sol.keys())[:10]} ...")
        return pd.DataFrame(columns=dimnames + ["VALUE"])

    data = []
    for idx, val in sol[varname].items():

        # Make sure idx is always a tuple, even for 1-D variables
        if not isinstance(idx, tuple):
            idx = (idx,)

        # If the tuple is shorter than dimnames, pad with None
        idx_padded = list(idx) + [None] * (len(dimnames) - len(idx))

        row = {dimnames[i]: idx_padded[i] for i in range(len(dimnames))}
        row["VALUE"] = val
        data.append(row)

    return pd.DataFrame(data)


def inspect_sol(sol: dict) -> pd.DataFrame:
    """
    Inspect the sol dictionary and return a summary DataFrame showing:
      - Every variable name found in the .sol file
      - How many entries it has (gives a sense of its dimensions)
      - Which plotting function can use it
      - Whether the variable has any non-zero values (useful = True/False)

    This is designed to be run as a Jupyter cell right after load_solution()
    so you can see exactly what is available before calling any plot function.
    Running this first prevents the "Variable not found" warning because you
    will know in advance which variable names to pass to the plot functions.

    Parameters
    ----------
    sol : the sol dictionary produced by load_solution()

    Returns
    -------
    df_inspect : DataFrame with columns:
                   VARIABLE | ENTRIES | NON_ZERO | PLOT_FUNCTION | NOTES

    Example (Jupyter)
    -----------------
        sol = load_solution(solver=solver_selec, sol_file=sol_file)
        df_inspect = inspect_sol(sol)
        df_inspect          # displays as a table in Jupyter
    """

    # Map each known OSeMOSYS variable to the plot function that uses it.
    # If a variable is in the sol but not in this map it gets "—" (unmapped).
    plot_function_map = {
        # Capacity variables → plot_capacity()
        "TotalCapacityAnnual"               : "plot_capacity()",
        "NewCapacity"                        : "plot_capacity()",
        "AccumulatedNewCapacity"             : "plot_capacity()",
        "NumberOfNewTechnologyUnits"         : "plot_capacity()",
        "ResidualCapacity"                   : "plot_capacity()",

        # Generation / activity variables → plot_generation()
        "ProductionByTechnology"             : "plot_generation()",
        "ProductionByTechnologyAnnual"       : "plot_generation_annual()",
        "RateOfActivity"                     : "plot_generation()  ← use if Production* missing",
        "RateOfProductionByTechnology"       : "plot_generation()",
        "UseByTechnology"                    : "plot_generation()",
        "UseByTechnologyAnnual"              : "plot_generation()",
        "TotalAnnualTechnologyActivityByMode": "plot_generation()",

        # Cost variables → plot_total_discounted_cost()
        "TotalDiscountedCost"                : "plot_total_discounted_cost()",
        "DiscountedCapitalInvestment"        : "plot_total_discounted_cost()",
        "DiscountedOperatingCost"            : "plot_total_discounted_cost()",
        "CapitalInvestment"                  : "plot_total_discounted_cost()",
        "OperatingCost"                      : "plot_total_discounted_cost()",
        "AnnualFixedOperatingCost"           : "plot_total_discounted_cost()",
        "AnnualVariableOperatingCost"        : "plot_total_discounted_cost()",
        "TotalDiscountedCostByTechnology"    : "plot_total_discounted_cost()",
        "RecoveryValue"                      : "plot_total_discounted_cost()",

        # Emissions variables → plot_emissions()
        "AnnualEmissions"                    : "plot_emissions()",
        "AnnualTechnologyEmission"           : "plot_emissions()",
        "TotalAnnualEmissions"               : "plot_emissions()",
        "DiscountedTechnologyEmissionsPenalty": "plot_emissions()",
    }

    rows = []
    for varname in sorted(sol.keys()):
        entries   = sol[varname]
        n_entries = len(entries)

        # Count how many entries have a value above a small threshold
        n_nonzero = sum(1 for v in entries.values() if abs(v) > 1e-9)

        plot_fn = plot_function_map.get(varname, "— not mapped to a plot function")

        # Flag variables that exist but are entirely zero — these won't produce
        # visible bars in any chart, which can be confusing
        if n_nonzero == 0:
            note = "⚠ all values are zero"
        elif varname not in plot_function_map:
            note = "ℹ available but no plot function defined yet"
        else:
            note = "✓ ready to plot"

        rows.append({
            "VARIABLE"      : varname,
            "ENTRIES"       : n_entries,
            "NON_ZERO"      : n_nonzero,
            "PLOT_FUNCTION" : plot_fn,
            "NOTE"          : note,
        })

    df_inspect = pd.DataFrame(rows)

    # Print a compact summary to the console / Jupyter output
    print("=" * 70)
    print(f"  SOL FILE INSPECTION  —  {len(sol)} variables found")
    print("=" * 70)
    print(f"  {'VARIABLE':<45} {'ENTRIES':>8}  {'NON_ZERO':>8}  NOTE")
    print("-" * 70)
    for _, row in df_inspect.iterrows():
        print(f"  {row['VARIABLE']:<45} {row['ENTRIES']:>8}  {row['NON_ZERO']:>8}  {row['NOTE']}")
    print("=" * 70)

    # Highlight variables the plotting functions expect but that are MISSING
    expected = set(plot_function_map.keys())
    found    = set(sol.keys())
    missing  = expected - found
    if missing:
        print("\n  Variables expected by plot functions but NOT in this .sol file:")
        for m in sorted(missing):
            print(f"    ✗  {m}  →  {plot_function_map[m]}")
        print()

    return df_inspect



