def _generate_shades(hex_color: str, n: int) -> list:
    """
    Generate n visually distinct shades of a given hex colour.
    Shades range from slightly dark to lighter so bars are readable.
    """
    hex_color = hex_color.lstrip("#")
    r, g, b = (int(hex_color[i:i+2], 16) / 255 for i in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(r, g, b)

    shades = []
    for i in range(n):
        # Vary luminosity between 0.35 (dark) and 0.70 (light)
        li = 0.35 + 0.35 * i / max(1, n - 1)
        # Keep saturation stable for thermal (greyscale) family
        si = s if s < 0.2 else min(1.0, s * 1.05)
        ri, gi, bi = colorsys.hls_to_rgb(h, li, si)
        shades.append(f"#{int(ri*255):02x}{int(gi*255):02x}{int(bi*255):02x}")

    return shades


def build_color_map(families: dict, base_colors: dict) -> dict:
    """
    Build a {technology_name: hex_color} mapping from the family definitions.
    Technologies not listed in any family will get a grey fallback.
    """
    color_map = {}
    for family_name, technologies in families.items():
        base = base_colors.get(family_name, "#AAAAAA")
        shades = _generate_shades(base, len(technologies))
        for tech, color in zip(technologies, shades):
            color_map[tech] = color
    return color_map


