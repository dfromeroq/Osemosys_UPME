def load_solution(solver: str, sol_file: str,
                  region_csv: str = None,
                  tech_csv:   str = None,
                  fuel_csv:   str = None) -> dict:
    """
    Master function: reads a .sol file for any supported solver and returns
    the unified `sol` dictionary.

    Parameters
    ----------
    solver     : one of "glpk", "highs", "gurobi"  (case-insensitive)
    sol_file   : path to the .sol file
    region_csv : optional CSV with a VALUE column listing region names.
                 If provided, region names are read from here instead of
                 being guessed from the sol file. Recommended when region
                 names contain underscores.
    tech_csv   : optional CSV with a VALUE column listing technology names.
                 Strongly recommended — prevents names like BACKSTOP_1 from
                 being split incorrectly at the underscore.
    fuel_csv   : optional CSV with a VALUE column listing fuel names.

    Returns
    -------
    sol : dict  →  { "VariableName": { (index_tuple): value, ... }, ... }
    """

    solver = solver.lower().strip()

    # Step 1: Read the file with the appropriate reader
    if solver == "gurobi":
        df = read_gurobi_sol(sol_file)
    elif solver == "highs":
        df = read_highs_sol(sol_file)
    elif solver == "glpk":
        df = read_glpk_sol(sol_file)
    else:
        raise ValueError(
            f"Unknown solver '{solver}'. Choose from: 'glpk', 'highs', 'gurobi'"
        )

    if df.empty:
        print(f"WARNING: No data was read from '{sol_file}'. Check the file path and format.")
        return {}

    # Step 2: Parse technology/fuel/region names for smart index splitting.
    # If a CSV is provided we use it; otherwise we fall back to auto-detection.
    tech_set   = _load_name_set(tech_csv)
    fuel_set   = _load_name_set(fuel_csv)
    region_set = _load_name_set(region_csv) if region_csv else _infer_region_set(df)

    print(f"  Name sets loaded — regions: {len(region_set)}, "
          f"technologies: {len(tech_set)}, fuels: {len(fuel_set)}")

    # Step 3: Convert the DataFrame into the structured sol dictionary
    sol = _dataframe_to_sol_dict(df, tech_set, fuel_set, region_set)

    print(f"[load_solution] Loaded {len(sol)} variable types. "
          f"Solver: {solver.upper()}")
    return sol


def _load_name_set(csv_path: str) -> set:
    """
    Helper: load a set of names from a CSV that has a 'VALUE' column.
    Returns an empty set if the path is None or the file doesn't exist.
    """
    if csv_path is None:
        return set()
    try:
        return set(pd.read_csv(csv_path)["VALUE"].astype(str))
    except Exception as e:
        print(f"  WARNING: Could not read name CSV '{csv_path}': {e}")
        return set()


def _infer_region_set(df: pd.DataFrame) -> set:
    """
    Helper: try to guess region names from the sol DataFrame.
    Regions are the first token inside every set of parentheses.
    We take the most common ones as the likely region names.
    """
    region_candidates = {}
    for name in df["Name"]:
        # Extract what's inside the brackets
        match = re.search(r'\((.+)\)', name)
        if not match:
            continue
        first_token = match.group(1).split("_")[0]
        region_candidates[first_token] = region_candidates.get(first_token, 0) + 1

    # Keep tokens that appear in more than 5% of rows (likely real region names)
    threshold = max(1, len(df) * 0.05)
    return {k for k, v in region_candidates.items() if v >= threshold}


