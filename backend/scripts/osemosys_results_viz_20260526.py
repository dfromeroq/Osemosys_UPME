def _save_matplotlib_bar(df: pd.DataFrame,
                          x_col: str,
                          y_col: str,
                          color_col: str,
                          title: str,
                          xlabel: str,
                          ylabel: str,
                          filepath: Path,
                          color_map: dict = None,
                          figsize: tuple = (14, 6),
                          x_order: list = None) -> None:
    """
    Save a stacked bar chart as a static PNG using Matplotlib.

    This is a shared helper called by every plot function so the Matplotlib
    styling is consistent across all charts.

    Parameters
    ----------
    df        : tidy DataFrame — one row per (x_col, color_col) combination
    x_col     : column for the x-axis (e.g. "YEAR")
    y_col     : column for the bar height (e.g. "VALUE")
    color_col : column used to colour/stack bars (e.g. "TECHNOLOGY")
    title     : chart title
    xlabel    : x-axis label
    ylabel    : y-axis label
    filepath  : full Path where the PNG will be saved
    color_map : optional {label: hex_color} dict — uses tab20 palette if None
    figsize   : figure size in inches (width, height)
    x_order   : explicit order for x-axis categories; inferred if None
    """

    # ── Pivot to wide format for stacked bar ─────────────────────────────────
    # Matplotlib's bar chart needs one column per stack layer
    if x_order is None:
        x_order = sorted(df[x_col].unique())

    categories = df[color_col].unique()

    pivot = (
        df.pivot_table(index=x_col, columns=color_col, values=y_col, aggfunc="sum")
        .reindex(x_order)              # enforce x order
        .fillna(0)
    )

    # ── Assign colours ────────────────────────────────────────────────────────
    # Use the shared COLOR_MAP if provided; fall back to tab20 for unknowns
    cmap_fallback = plt.get_cmap("tab20")
    colors = []
    for i, col in enumerate(pivot.columns):
        if color_map and col in color_map:
            colors.append(color_map[col])
        else:
            colors.append(cmap_fallback(i % 20))

    # ── Draw stacked bars ─────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=figsize)

    bottom = [0.0] * len(pivot)
    x_positions = range(len(pivot))

    for col, color in zip(pivot.columns, colors):
        values = pivot[col].values
        ax.bar(x_positions, values, bottom=bottom,
               label=col, color=color, width=0.75, edgecolor="none")
        bottom = [b + v for b, v in zip(bottom, values)]

    # ── Formatting ────────────────────────────────────────────────────────────
    ax.set_title(title, fontsize=13, fontweight="bold", pad=12)
    ax.set_xlabel(xlabel, fontsize=10)
    ax.set_ylabel(ylabel, fontsize=10)
    ax.set_xticks(list(x_positions))
    ax.set_xticklabels([str(x) for x in pivot.index],
                       rotation=45, ha="right", fontsize=8)
    ax.yaxis.set_major_formatter(mticker.FuncFormatter(
        lambda v, _: f"{v:,.0f}"   # thousands separator on y-axis
    ))
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.grid(axis="y", linestyle="--", alpha=0.4)

    # Legend outside the plot on the right
    ax.legend(
        loc="upper left",
        bbox_to_anchor=(1.01, 1),
        fontsize=8,
        frameon=False,
        ncol=max(1, len(categories) // 25 + 1),  # multi-column if many techs
    )

    plt.tight_layout()
    fig.savefig(str(filepath), dpi=150, bbox_inches="tight")
    plt.close(fig)   # free memory — important in Jupyter to avoid figure accumulation
    print(f"  Graph saved: {filepath}")

