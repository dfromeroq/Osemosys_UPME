# ================================================================================
#
# Several important OSeMOSYS reporting variables are NOT written to the .sol
# file because the solver treats them as intermediate expressions.
# This section recalculates them using the standard OSeMOSYS formulas.
#
# All calculations use pandas merge + groupby — NO Python loops over large
# dictionaries.  This keeps runtime under a few seconds even for large models.
#
# REQUIRED INPUT PARAMETERS (read from csv_dir):
#   OperationalLife.csv       → for AccumulatedNewCapacity / TotalCapacityAnnual
#   ResidualCapacity.csv      → for TotalCapacityAnnual
#   YearSplit.csv             → for ProductionByTechnology / Emissions
#   OutputActivityRatio.csv   → for ProductionByTechnology
#   EmissionActivityRatio.csv → for AnnualTechnologyEmission
# ================================================================================


def _read_csv_df(csv_dir: str, filename: str) -> pd.DataFrame:
    """
    Read a parameter CSV and return it as a DataFrame with standardised
    uppercase column names.  Returns an empty DataFrame if the file is missing.
    """
    path = Path(csv_dir) / filename
    if not path.exists():
        print(f"  WARNING: '{filename}' not found in '{csv_dir}' — "
              f"some derived variables will be skipped.")
        return pd.DataFrame()

    df = pd.read_csv(path)
    df.columns = [c.strip().upper() for c in df.columns]  # normalise column names
    return df


def _sol_var_to_df_raw(sol: dict, varname: str, colnames: list) -> pd.DataFrame:
    """
    Convert one variable from the sol dict into a DataFrame using the
    positional convention:
        col[0]  = region   (always index[0])
        col[-1] = year     (always index[-1])
        cols in between    = remaining dimensions, rejoined with "_" if needed

    This is the safe version that handles keys of any length (avoids the
    "too many values to unpack" error caused by underscore-containing names).
    """
    rows = []
    for idx, val in sol[varname].items():
        if not isinstance(idx, tuple):
            idx = (idx,)

        n = len(colnames)   # expected number of columns (excluding VALUE)

        if len(idx) == n:
            # Key length matches exactly — use directly
            row = list(idx)
        elif len(idx) > n:
            # More tokens than expected — collapse the middle ones
            # e.g. (RE1, BACKSTOP, 1, 2022) with colnames [R,T,Y] → (RE1, BACKSTOP_1, 2022)
            row = [idx[0]]                                          # first = region
            row.append("_".join(str(x) for x in idx[1:n-1]))       # middle collapsed
            row.append(idx[-1])                                     # last = year
        else:
            # Fewer tokens than expected — pad with empty strings
            row = list(idx) + [""] * (n - len(idx))

        rows.append(row + [val])

    if not rows:
        return pd.DataFrame(columns=colnames + ["VALUE"])

    df = pd.DataFrame(rows, columns=colnames + ["VALUE"])
    df["VALUE"] = pd.to_numeric(df["VALUE"], errors="coerce").fillna(0.0)
    return df


def derive_variables(sol: dict, csv_dir: str) -> dict:
    """
    Calculate all important derived variables and add them to sol.

    Uses vectorised pandas operations — no slow Python loops.
    Typically completes in 2–10 seconds even for large models.

    Parameters
    ----------
    sol     : the sol dictionary from load_solution()
    csv_dir : folder containing the input parameter CSV files

    Variables added:
        AccumulatedNewCapacity        ← NewCapacity + OperationalLife
        TotalCapacityAnnual           ← AccumulatedNewCapacity + ResidualCapacity
        ProductionByTechnology        ← RateOfActivity × OutputActivityRatio × YearSplit
        ProductionByTechnologyAnnual  ← ProductionByTechnology summed over timeslices
        AnnualTechnologyEmission      ← RateOfActivity × EmissionActivityRatio × YearSplit
        TotalAnnualEmissions          ← AnnualTechnologyEmission summed over technologies
    """
    import time
    t0 = time.time()

    print("\n[derive_variables] Calculating derived variables (vectorised)...")
    print(f"  CSV directory: '{Path(csv_dir).absolute()}'")

    # ── Read parameter CSVs as DataFrames ────────────────────────────────────
    df_op_life   = _read_csv_df(csv_dir, "OperationalLife.csv")
    df_res_cap   = _read_csv_df(csv_dir, "ResidualCapacity.csv")
    df_ys        = _read_csv_df(csv_dir, "YearSplit.csv")
    df_oar       = _read_csv_df(csv_dir, "OutputActivityRatio.csv")
    df_ear       = _read_csv_df(csv_dir, "EmissionActivityRatio.csv")

    # ── Convert sol variables to DataFrames ──────────────────────────────────
    # NewCapacity:    (REGION, TECHNOLOGY, YEAR)
    # RateOfActivity: (REGION, TIMESLICE, TECHNOLOGY, MODE_OF_OPERATION, YEAR)

    df_nc  = _sol_var_to_df_raw(sol, "NewCapacity",
                                 ["REGION", "TECHNOLOGY", "YEAR"])              if "NewCapacity" in sol else pd.DataFrame()

    df_roa = _sol_var_to_df_raw(sol, "RateOfActivity",
                                 ["REGION", "TIMESLICE", "TECHNOLOGY",
                                  "MODE_OF_OPERATION", "YEAR"])              if "RateOfActivity" in sol else pd.DataFrame()

    # ── Normalise column types across all DataFrames ─────────────────────────
    # The sol dict stores everything as strings (keys come from text parsing).
    # The CSV files may have integers in columns like MODE_OF_OPERATION or YEAR.
    # Strategy:
    #   YEAR → integer  (needed for arithmetic in capacity accumulation)
    #   All other index columns → string  (safe for merging with sol-derived data)
    # This must be done BEFORE any merge to prevent type mismatch errors.

    all_dfs = [df_nc, df_roa, df_op_life, df_res_cap, df_ys, df_oar, df_ear]

    for df in all_dfs:
        if df.empty:
            continue
        # Cast YEAR to int
        if "YEAR" in df.columns:
            df["YEAR"] = df["YEAR"].astype(str).str.strip().astype(int)
        # Cast all other non-VALUE columns to string
        for col in df.columns:
            if col not in ("YEAR", "VALUE"):
                df[col] = df[col].astype(str).str.strip()

    # ── 1. AccumulatedNewCapacity ─────────────────────────────────────────────
    # For each (region, technology, year Y):
    #   sum NewCapacity[r,t,yy] for all yy where  0 <= Y - yy < OperationalLife[r,t]
    #
    # Vectorised approach:
    #   Cross-join NewCapacity years with all model years, then filter by
    #   the operational life window and sum.

    if not df_nc.empty and not df_op_life.empty:
        t1 = time.time()

        # Rename VALUE in NewCapacity to NC_VALUE to avoid collision after merge
        df_nc2 = df_nc.rename(columns={"VALUE": "NC_VALUE", "YEAR": "BUILD_YEAR"})

        # Standardise OperationalLife column names
        ol_cols = list(df_op_life.columns)
        ol_val_col = [c for c in ol_cols if c == "VALUE"][0]
        ol_idx_cols = [c for c in ol_cols if c != "VALUE"]
        df_ol = df_op_life.rename(columns={ol_val_col: "OP_LIFE"})

        # All unique model years (for the "current year" Y axis)
        all_years = sorted(df_nc["YEAR"].unique())
        df_years  = pd.DataFrame({"YEAR": all_years})

        # Cross-join: every (region, tech, build_year) × every model year
        df_cross = df_nc2.merge(df_years, how="cross")

        # Join OperationalLife
        join_cols = [c for c in ol_idx_cols if c in df_cross.columns]
        df_cross  = df_cross.merge(df_ol[join_cols + ["OP_LIFE"]],
                                   on=join_cols, how="left")
        df_cross["OP_LIFE"] = df_cross["OP_LIFE"].fillna(0)

        # Keep rows within the operational window: 0 <= Y - build_year < OP_LIFE
        df_cross["AGE"] = df_cross["YEAR"] - df_cross["BUILD_YEAR"]
        df_window = df_cross[
            (df_cross["AGE"] >= 0) & (df_cross["AGE"] < df_cross["OP_LIFE"])
        ]

        # Sum NewCapacity over all valid build years for each (region, tech, year)
        df_acc = (
            df_window
            .groupby(["REGION", "TECHNOLOGY", "YEAR"], as_index=False)["NC_VALUE"]
            .sum()
            .rename(columns={"NC_VALUE": "VALUE"})
        )

        # Store back in sol
        sol["AccumulatedNewCapacity"] = {
            (r["REGION"], r["TECHNOLOGY"], str(r["YEAR"])): r["VALUE"]
            for _, r in df_acc.iterrows()
        }
        print(f"  ✓ AccumulatedNewCapacity       ({len(df_acc)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        df_acc = pd.DataFrame()
        print("  ✗ AccumulatedNewCapacity       — needs NewCapacity + OperationalLife.csv")

    # ── 2. TotalCapacityAnnual ────────────────────────────────────────────────
    # TotalCapacityAnnual[r,t,y] = AccumulatedNewCapacity[r,t,y]
    #                             + ResidualCapacity[r,t,y]

    if not df_acc.empty and not df_res_cap.empty:
        t1 = time.time()

        df_res = df_res_cap.copy()
        # Standardise ResidualCapacity column names
        res_cols = list(df_res.columns)
        res_val  = [c for c in res_cols if c == "VALUE"][0]
        df_res   = df_res.rename(columns={res_val: "RES_VALUE"})
        res_idx  = [c for c in res_cols if c != "VALUE"]

        join_cols = [c for c in res_idx if c in df_acc.columns]
        df_total  = df_acc.merge(df_res[join_cols + ["RES_VALUE"]],
                                 on=join_cols, how="left")
        df_total["RES_VALUE"] = df_total["RES_VALUE"].fillna(0.0)
        df_total["VALUE"]     = df_total["VALUE"] + df_total["RES_VALUE"]
        df_total = df_total[["REGION", "TECHNOLOGY", "YEAR", "VALUE"]]

        sol["TotalCapacityAnnual"] = {
            (r["REGION"], r["TECHNOLOGY"], str(r["YEAR"])): r["VALUE"]
            for _, r in df_total.iterrows()
        }
        print(f"  ✓ TotalCapacityAnnual          ({len(df_total)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        print("  ✗ TotalCapacityAnnual          — needs AccumulatedNewCapacity + ResidualCapacity.csv")

    # ── 3. ProductionByTechnology ─────────────────────────────────────────────
    # ProductionByTechnology[r,l,t,f,y] =
    #   SUM_m( RateOfActivity[r,l,t,m,y] × OutputActivityRatio[r,t,f,m,y] )
    #   × YearSplit[l,y]
    #
    # Vectorised: merge RateOfActivity with OutputActivityRatio on
    # (REGION, TECHNOLOGY, MODE_OF_OPERATION, YEAR), multiply, then multiply
    # by YearSplit.

    if not df_roa.empty and not df_oar.empty and not df_ys.empty:
        t1 = time.time()

        # Standardise column names in parameter DataFrames
        df_oar2 = df_oar.copy()
        df_oar2.columns = [c.strip().upper() for c in df_oar2.columns]
        oar_val_col = "VALUE"
        df_oar2 = df_oar2.rename(columns={oar_val_col: "OAR"})

        df_ys2 = df_ys.copy()
        df_ys2.columns = [c.strip().upper() for c in df_ys2.columns]
        df_ys2 = df_ys2.rename(columns={"VALUE": "YEARSPLIT"})

        # Join RateOfActivity × OutputActivityRatio
        # Match on: REGION, TECHNOLOGY, MODE_OF_OPERATION, YEAR
        # OAR also has FUEL which becomes a new dimension in the result
        merge_cols = [c for c in ["REGION", "TECHNOLOGY", "MODE_OF_OPERATION", "YEAR"]
                      if c in df_roa.columns and c in df_oar2.columns]

        df_prod = df_roa.merge(df_oar2, on=merge_cols, how="inner")
        df_prod = df_prod.rename(columns={"VALUE": "ROA"})

        # Join YearSplit on (TIMESLICE, YEAR)
        ys_join = [c for c in ["TIMESLICE", "YEAR"]
                   if c in df_prod.columns and c in df_ys2.columns]
        df_prod = df_prod.merge(df_ys2, on=ys_join, how="left")
        df_prod["YEARSPLIT"] = df_prod["YEARSPLIT"].fillna(0.0)

        # Calculate production
        df_prod["VALUE"] = df_prod["ROA"] * df_prod["OAR"] * df_prod["YEARSPLIT"]

        # Aggregate over MODE_OF_OPERATION (sum modes)
        group_cols = [c for c in ["REGION", "TIMESLICE", "TECHNOLOGY", "FUEL", "YEAR"]
                      if c in df_prod.columns]
        df_prod = df_prod.groupby(group_cols, as_index=False)["VALUE"].sum()

        # Drop near-zero values to keep the dict lean
        df_prod = df_prod[df_prod["VALUE"].abs() > 1e-9]

        sol["ProductionByTechnology"] = {
            tuple(str(r[c]) for c in group_cols): r["VALUE"]
            for _, r in df_prod.iterrows()
        }
        print(f"  ✓ ProductionByTechnology       ({len(df_prod)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        df_prod = pd.DataFrame()
        print("  ✗ ProductionByTechnology       — needs RateOfActivity + "
              "OutputActivityRatio.csv + YearSplit.csv")

    # ── 4. ProductionByTechnologyAnnual ───────────────────────────────────────
    # Sum ProductionByTechnology over all timeslices within each year.

    if not df_prod.empty:
        t1 = time.time()

        group_cols_ann = [c for c in ["REGION", "TECHNOLOGY", "FUEL", "YEAR"]
                          if c in df_prod.columns]
        df_prod_ann = df_prod.groupby(group_cols_ann, as_index=False)["VALUE"].sum()
        df_prod_ann = df_prod_ann[df_prod_ann["VALUE"].abs() > 1e-9]

        sol["ProductionByTechnologyAnnual"] = {
            tuple(str(r[c]) for c in group_cols_ann): r["VALUE"]
            for _, r in df_prod_ann.iterrows()
        }
        print(f"  ✓ ProductionByTechnologyAnnual ({len(df_prod_ann)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        df_prod_ann = pd.DataFrame()
        print("  ✗ ProductionByTechnologyAnnual — needs ProductionByTechnology")

    # ── 5. AnnualTechnologyEmission ───────────────────────────────────────────
    # AnnualTechnologyEmission[r,t,e,y] =
    #   SUM_l SUM_m( RateOfActivity[r,l,t,m,y]
    #                × EmissionActivityRatio[r,t,e,m,y]
    #                × YearSplit[l,y] )
    #
    # Same pattern as ProductionByTechnology but with EmissionActivityRatio.

    if not df_roa.empty and not df_ear.empty and not df_ys.empty:
        t1 = time.time()

        df_ear2 = df_ear.copy()
        df_ear2.columns = [c.strip().upper() for c in df_ear2.columns]
        df_ear2 = df_ear2.rename(columns={"VALUE": "EAR"})

        df_ys2 = df_ys.copy()
        df_ys2.columns = [c.strip().upper() for c in df_ys2.columns]
        df_ys2 = df_ys2.rename(columns={"VALUE": "YEARSPLIT"})

        merge_cols = [c for c in ["REGION", "TECHNOLOGY", "MODE_OF_OPERATION", "YEAR"]
                      if c in df_roa.columns and c in df_ear2.columns]

        df_emis = df_roa.merge(df_ear2, on=merge_cols, how="inner")
        df_emis = df_emis.rename(columns={"VALUE": "ROA"})

        ys_join = [c for c in ["TIMESLICE", "YEAR"]
                   if c in df_emis.columns and c in df_ys2.columns]
        df_emis = df_emis.merge(df_ys2, on=ys_join, how="left")
        df_emis["YEARSPLIT"] = df_emis["YEARSPLIT"].fillna(0.0)
        df_emis["VALUE"]     = df_emis["ROA"] * df_emis["EAR"] * df_emis["YEARSPLIT"]

        # Aggregate over timeslice and mode → annual technology emission
        group_cols_emis = [c for c in ["REGION", "TECHNOLOGY", "EMISSION", "YEAR"]
                           if c in df_emis.columns]
        df_emis = df_emis.groupby(group_cols_emis, as_index=False)["VALUE"].sum()
        df_emis = df_emis[df_emis["VALUE"].abs() > 1e-9]

        sol["AnnualTechnologyEmission"] = {
            tuple(str(r[c]) for c in group_cols_emis): r["VALUE"]
            for _, r in df_emis.iterrows()
        }
        print(f"  ✓ AnnualTechnologyEmission     ({len(df_emis)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        df_emis = pd.DataFrame()
        print("  ✗ AnnualTechnologyEmission     — needs RateOfActivity + "
              "EmissionActivityRatio.csv + YearSplit.csv")

    # ── 6. TotalAnnualEmissions ───────────────────────────────────────────────
    # Sum AnnualTechnologyEmission over all technologies.

    if not df_emis.empty:
        t1 = time.time()

        group_cols_te = [c for c in ["REGION", "EMISSION", "YEAR"]
                         if c in df_emis.columns]
        df_total_emis = df_emis.groupby(group_cols_te, as_index=False)["VALUE"].sum()
        df_total_emis = df_total_emis[df_total_emis["VALUE"].abs() > 1e-9]

        sol["TotalAnnualEmissions"] = {
            tuple(str(r[c]) for c in group_cols_te): r["VALUE"]
            for _, r in df_total_emis.iterrows()
        }
        print(f"  ✓ TotalAnnualEmissions         ({len(df_total_emis)} entries, "
              f"{time.time()-t1:.1f}s)")
    else:
        print("  ✗ TotalAnnualEmissions         — needs AnnualTechnologyEmission")

    print(f"\n[derive_variables] Done in {time.time()-t0:.1f}s total.\n")
    return sol


