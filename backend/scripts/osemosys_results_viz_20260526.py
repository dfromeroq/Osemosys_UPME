    # This loop reads the variables_to_plot list from USER SETTINGS and calls
    # the right plot function for each entry.
    # To skip a chart: comment out its line in variables_to_plot at the top.
    # To add a chart:  uncomment or add a new line there.

    # Dispatcher: maps the short plot-type label to the actual function
    plot_dispatcher = {
        "capacity"          : plot_capacity,
        "generation"        : plot_generation,
        "generation_annual" : plot_generation_annual,
        "cost"              : plot_total_discounted_cost,
        "emissions"         : plot_emissions,
    }

